func pickPose(rng *rand.Rand) pose { return poseBank[rng.Intn(len(poseBank))] }

// scrubLegacyPoseSources relabels rolebot_generated.poseSource rows that hold a character
// name instead of a pose number, by matching the pilot's twelve character_ numbers against
// the bank (with a small tolerance). Unmatched rows are blanked. One pass leaves nothing in
// the legacy format, so later boots do no work.
func (m *Mod) scrubLegacyPoseSources(ctx context.Context) {
	rows, err := m.db.QueryContext(ctx, `
		SELECT g.characterID, c.headRotation1, c.headRotation2, c.camPos1, c.camPos2
		FROM rolebot_generated g
		JOIN character_ c ON c.characterID = g.characterID
		WHERE g.poseSource <> '' AND g.poseSource NOT LIKE 'pose %'`)
	if err != nil {
		rlogf("rolebots: scrub pose sources: %v", err)
		return
	}
	type row struct {
		id                 int64
		h1, h2, cam1, cam2 float64
	}
	var pending []row
	for rows.Next() {
		var r row
		if err := rows.Scan(&r.id, &r.h1, &r.h2, &r.cam1, &r.cam2); err != nil {
			rows.Close()
			rlogf("rolebots: scrub pose sources: %v", err)
			return
		}
		pending = append(pending, r)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		rlogf("rolebots: scrub pose sources: %v", err)
		return
	}

	const tol = 0.002
	relabelled := 0
	for _, r := range pending {
		for _, p := range poseBank {
			if math.Abs(p.Head[0]-r.h1) < tol && math.Abs(p.Head[1]-r.h2) < tol &&
				math.Abs(p.Cam[0]-r.cam1) < tol && math.Abs(p.Cam[1]-r.cam2) < tol {
				if _, err := m.db.ExecContext(ctx,
					`UPDATE rolebot_generated SET poseSource = ? WHERE characterID = ?`, p.ID, r.id); err != nil {
					rlogf("rolebots: scrub pose sources: %v", err)
					return
				}
				relabelled++
				break
			}
		}
	}
	// The backstop: whatever the match pass did not claim loses its label.
	res, err := m.db.ExecContext(ctx, `
		UPDATE rolebot_generated SET poseSource = ''
		WHERE poseSource <> '' AND poseSource NOT LIKE 'pose %'`)
	if err != nil {
		rlogf("rolebots: scrub pose sources: %v", err)
		return
	}
	if n, _ := res.RowsAffected(); n > 0 || relabelled > 0 {
		rlogf("rolebots: pose sources anonymised — %d relabelled by number, %d blanked", relabelled, n)
	}
}
