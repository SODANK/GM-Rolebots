# mod-rebuild.ps1 — build the GuriMoon server WITH the rolebots module
# compiled in, WITHOUT modifying the server repository.
#
# Mechanism: `go build -overlay` maps two kinds of virtual files into the
# build:
#   1. modules/modules.go            -> build/modules_enabled.go (adds the
#                                       blank import that registers rolebots)
#   2. modules/rolebots/**/*.go      -> the .go sources in this repo's
#                                       rolebots/ tree
# Nothing is copied into the server repo; removing the module is just
# running the server's `rebuild.bat core` (a plain build without the overlay).
#
# Usage:
#   .\mod-rebuild.ps1              # build + replace server exe (server repo root)
#   .\mod-rebuild.ps1 -Check      # compile-check only; exe goes to build\, server untouched
#   .\mod-rebuild.ps1 -ServerRepo D:\other\GuriMoon   # server repo elsewhere
#   .\mod-rebuild.ps1 -OverlayOnly  # write build\overlay.json only (used by the
#                                   # server repo's root rebuild.ps1)
#
# -ServerRepo defaults to two folders up, which is the server repo when this
# folder sits in <server repo>\modules\.

param(
    [string]$ServerRepo = "",
    [switch]$Check,
    # Write build\overlay.json and stop. This is the server repo's contract
    # for overlay modules: its root rebuild.ps1 calls every module with this
    # switch, merges the overlays and builds once with all of them.
    [switch]$OverlayOnly
)

$ErrorActionPreference = "Stop"
$ModRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
if ($ServerRepo -eq "") { $ServerRepo = Split-Path -Parent (Split-Path -Parent $ModRoot) }
$BuildDir = Join-Path $ModRoot "build"
if (-not (Test-Path $BuildDir)) { New-Item -ItemType Directory $BuildDir | Out-Null }

if (-not (Test-Path (Join-Path $ServerRepo "go.mod"))) {
    Write-Error "Server repo not found at $ServerRepo (no go.mod)"
}

# ── 1. Generated modules.go: enables the rolebots module ────────────────────
$modulesGo = @'
// Code generated by GM-RoleBot-mod/mod-rebuild.ps1. DO NOT EDIT.
// This file exists only inside the -overlay build; the on-disk
// modules/modules.go in the server repo is untouched.
package modules

import _ "gurimoon/modules/rolebots"
'@
$modulesEnabledPath = Join-Path $BuildDir "modules_enabled.go"
[System.IO.File]::WriteAllText($modulesEnabledPath, $modulesGo)

# ── 1b. Core seams ──────────────────────────────────────────────────────────
# This script used to PATCH core files at build time (anchored text inserts
# into esp/session.go, server/slash, db/marketdb.go, server/gangsta,
# server/lsc, seclaw/verdict.go, cmd/gurimoon/concord.go,
# secstatus_settings.go and main.go). Every one of those is in core now as an
# ordinary, nil-by-default seam or a core rule:
#   esp.Session.Bot, slash.ModuleCommand, gangsta ModuleOwns /
#   ModuleGangCandidate (server/gangsta/modulegang.go), lsc.ModuleChat
#   (server/lsc/modulechat.go), seclaw KillFacts.VictimOutlaw, the aggression
#   charge (cmd/gurimoon/aggressioncharge.go), passive sec decay off by
#   default, no NPC mineral bids, and ensureSystemLoaded
#   (cmd/gurimoon/systemload.go).
# The overlay below only ADDS files; it rewrites none. Do not reintroduce a
# text patch: put the seam in core instead.

$sessionBotModSrc = Join-Path $ModRoot "core\esp\sessionbot_mod.go"
$pvpBridgeSrc = Join-Path $ModRoot "core\modapi\pvpbridge_mod.go"
$pvpMainSrc = Join-Path $ModRoot "core\main\rolebotpvp_mod.go"
$botSpeakSrc = Join-Path $ModRoot "core\lsc\botspeak_mod.go"
$gangBridgeSrc = Join-Path $ModRoot "core\modapi\gangbridge_mod.go"
$gangMainSrc = Join-Path $ModRoot "core\main\rolebotgang_mod.go"
foreach ($p in @($sessionBotModSrc, $pvpBridgeSrc, $pvpMainSrc, $botSpeakSrc, $gangBridgeSrc, $gangMainSrc)) {
    if (-not (Test-Path $p)) { Write-Error "missing module source: $p" }
}

# Same list as mod-rebuild.sh (the POSIX build): a bridge file added here is
# added to its "Overlay map" section too.
# ── 2. Overlay map ──────────────────────────────────────────────────────────
$replace = @{}
$replace[(Join-Path $ServerRepo "modules\modules.go")] = $modulesEnabledPath
# A path with nothing behind it in the server repo: the overlay ADDS this
# file to the core esp package. Same mechanism that puts this whole module
# under modules\rolebots\, which does not exist on disk either.
$replace[(Join-Path $ServerRepo "esp\sessionbot_mod.go")] = $sessionBotModSrc
# The in-game browser kit (panel bands, icons, bars, YC dates) exported to
# the module's Corporate Portal sections. Wraps esp's unexported helpers;
# patches nothing.
$igbKitSrc = Join-Path $ModRoot "core\esp\igbkit_mod.go"
if (-not (Test-Path $igbKitSrc)) { Write-Error "Missing $igbKitSrc" }
$replace[(Join-Path $ServerRepo "esp\igbkit_mod.go")] = $igbKitSrc
$replace[(Join-Path $ServerRepo "modapi\pvpbridge_mod.go")] = $pvpBridgeSrc
$replace[(Join-Path $ServerRepo "cmd\gurimoon\rolebotpvp_mod.go")] = $pvpMainSrc
$replace[(Join-Path $ServerRepo "server\lsc\botspeak_mod.go")] = $botSpeakSrc
$replace[(Join-Path $ServerRepo "modapi\gangbridge_mod.go")] = $gangBridgeSrc
$replace[(Join-Path $ServerRepo "cmd\gurimoon\rolebotgang_mod.go")] = $gangMainSrc

# -- system-loading seam (space that exists ahead of a player) --------------
# The build is core's ensureSystemLoaded (cmd/gurimoon/systemload.go); these
# two files publish it, and the teardown, through modapi.SpaceHooks.
$spaceBridgeSrc = Join-Path $ModRoot "core\modapi\preloadbridge_mod.go"
$preloadMainSrc = Join-Path $ModRoot "core\main\rolebotpreload_mod.go"
foreach ($p in @($spaceBridgeSrc, $preloadMainSrc)) {
    if (-not (Test-Path $p)) { Write-Error "missing module source: $p" }
}
$replace[(Join-Path $ServerRepo "modapi\preloadbridge_mod.go")] = $spaceBridgeSrc
$replace[(Join-Path $ServerRepo "cmd\gurimoon\rolebotpreload_mod.go")] = $preloadMainSrc

# -- corporation push seam (bot CEOs) ----------------------------------------
# A CEO's writes are all existing evedb calls; what a module cannot reach is
# the push that goes with each one (notifyCorp and friends are unexported in
# package main). modapi.CorpHooks carries two thin closures installed from
# main's init(). A module-free rebuild drops both files.
$corpBridgeSrc = Join-Path $ModRoot "core\modapi\corpbridge_mod.go"
$corpMainSrc = Join-Path $ModRoot "core\main\rolebotcorp_mod.go"
foreach ($p in @($corpBridgeSrc, $corpMainSrc)) {
    if (-not (Test-Path $p)) { Write-Error "missing module source: $p" }
}
$replace[(Join-Path $ServerRepo "modapi\corpbridge_mod.go")] = $corpBridgeSrc
$replace[(Join-Path $ServerRepo "cmd\gurimoon\rolebotcorp_mod.go")] = $corpMainSrc

# -- drone seam (bot drones in space) ----------------------------------------
# launchDronesForPlayer is written against a player connection, so a module
# ship could carry drones and never launch one. modapi.DroneHooks carries
# launch / command / recall / lose closures installed from main's init();
# the drones themselves run on the core's own manager and callbacks. A
# module-free rebuild drops both files.
$droneBridgeSrc = Join-Path $ModRoot "core\modapi\dronebridge_mod.go"
$droneMainSrc = Join-Path $ModRoot "core\main\rolebotdrone_mod.go"
foreach ($p in @($droneBridgeSrc, $droneMainSrc)) {
    if (-not (Test-Path $p)) { Write-Error "missing module source: $p" }
}
$replace[(Join-Path $ServerRepo "modapi\dronebridge_mod.go")] = $droneBridgeSrc
$replace[(Join-Path $ServerRepo "cmd\gurimoon\rolebotdrone_mod.go")] = $droneMainSrc

# -- open-site seam (bots run the dungeons the core seeds) ------------------
# Everything about a live open site is unexported in package main, and the
# NPC build is written against a player connection. modapi.SiteHooks carries
# read / mark / build closures installed from main's init(); the trigger
# chain is replayed in the module (rolebots/sitewave.go). A module-free
# rebuild drops both files.
$siteBridgeSrc = Join-Path $ModRoot "core\modapi\sitebridge_mod.go"
$siteMainSrc = Join-Path $ModRoot "core\main\rolebotsite_mod.go"
foreach ($p in @($siteBridgeSrc, $siteMainSrc)) {
    if (-not (Test-Path $p)) { Write-Error "missing module source: $p" }
}
$replace[(Join-Path $ServerRepo "modapi\sitebridge_mod.go")] = $siteBridgeSrc
$replace[(Join-Path $ServerRepo "cmd\gurimoon\rolebotsite_mod.go")] = $siteMainSrc

# -- agent-mission seam (bots take, run and turn in agent missions) ----------
# The agent conversation is package main's handleAgentDoAction; these closures
# call it with no connection, and serve an accepted kill mission's pocket to
# the site seam under a negative site ID. A module-free
# rebuild drops both files.
$missionBridgeSrc = Join-Path $ModRoot "core\modapi\missionbridge_mod.go"
$missionMainSrc = Join-Path $ModRoot "core\main\rolebotmission_mod.go"
foreach ($p in @($missionBridgeSrc, $missionMainSrc)) {
    if (-not (Test-Path $p)) { Write-Error "missing module source: $p" }
}
$replace[(Join-Path $ServerRepo "modapi\missionbridge_mod.go")] = $missionBridgeSrc
$replace[(Join-Path $ServerRepo "cmd\gurimoon\rolebotmission_mod.go")] = $missionMainSrc

# -- corp allegiance (a player corporation's faction) ------------------------
# npc.StandingsMap knows only NPC corporations; this file adds SetCorpFaction
# so the module can declare a bot corporation's allegiance and the core's rats
# spare it. A module-free rebuild drops the file.
$corpFactionSrc = Join-Path $ModRoot "core\npc\corpfaction_mod.go"
if (-not (Test-Path $corpFactionSrc)) { Write-Error "missing module source: $corpFactionSrc" }
$replace[(Join-Path $ServerRepo "npc\corpfaction_mod.go")] = $corpFactionSrc

$srcRoot = Join-Path $ModRoot "rolebots"
if (-not (Test-Path $srcRoot)) { Write-Error "No rolebots\ source tree in $ModRoot" }
Get-ChildItem -Path $srcRoot -Recurse -Filter *.go | ForEach-Object {
    $rel = $_.FullName.Substring($srcRoot.Length).TrimStart('\')
    $virtual = Join-Path $ServerRepo ("modules\rolebots\" + $rel)
    $replace[$virtual] = $_.FullName
}

$overlay = @{ Replace = $replace } | ConvertTo-Json -Depth 5
$overlayPath = Join-Path $BuildDir "overlay.json"
[System.IO.File]::WriteAllText($overlayPath, $overlay)
Write-Host "overlay: $($replace.Count) file(s) mapped -> $overlayPath"

if ($OverlayOnly) { return }

# ── 3. Build ────────────────────────────────────────────────────────────────
Push-Location $ServerRepo
try {
    if ($Check) {
        $out = Join-Path $BuildDir "gurimoon-check.exe"
        Write-Host "=== compile check (server repo untouched) ==="
        go build -overlay $overlayPath -o $out .\cmd\gurimoon\
    } else {
        Write-Host "=== building server WITH rolebots module ==="
        go build -overlay $overlayPath .\cmd\gurimoon\
    }
    if ($LASTEXITCODE -ne 0) { throw "go build failed" }
    Write-Host "=== Build OK ==="
} finally {
    Pop-Location
}
