#!/bin/sh
# mod-rebuild.sh - build the GuriMoon server WITH the rolebots module
# compiled in, WITHOUT modifying the server repository.
#
# The POSIX counterpart of mod-rebuild.ps1 (Linux, macOS, Git Bash, the
# server's Dockerfile). Both scripts write the same build/overlay.json. The
# bridge files are listed by hand in both: a file added to the "Overlay map"
# section of one is added to the same section of the other.
#
# Mechanism: `go build -overlay` maps virtual files into the build:
#   1. modules/modules.go        -> build/modules_enabled.go (the blank import
#                                   that registers rolebots)
#   2. core seam bridge files    -> core/** in this repo, ADDED to the core
#                                   packages (esp, modapi, server/lsc, main)
#   3. modules/rolebots/**/*.go  -> rolebots/ in this repo
# Nothing is copied into the server repo and no core file is rewritten; a
# module that needs a hook gets a nil-by-default seam in core instead.
#
# Usage:
#   ./mod-rebuild.sh                     build + replace server exe (rolebots only)
#   ./mod-rebuild.sh --check             compile check; exe goes to build/, server untouched
#   ./mod-rebuild.sh --overlay-only --server-repo <abs path>
#                                        write build/overlay.json only. This is the
#                                        server repo's contract: its root rebuild.sh
#                                        calls every module this way, merges the
#                                        overlays (cmd/overlaymerge) and builds once.
#
# A .disabled file in this folder is honoured by the root script, which never
# calls this one then. build-tags.txt, if present, is read by the root script.

set -eu

mode="build"
server=""

while [ $# -gt 0 ]; do
    case "$1" in
        --overlay-only) mode="overlay" ;;
        --check) mode="check" ;;
        --server-repo) server="$2"; shift ;;
        *) echo "unknown argument '$1'" >&2; exit 1 ;;
    esac
    shift
done

# abspath DIR: absolute path with forward slashes. Under Git Bash / MSYS the
# shell's /e/... form is unknown to go.exe, so cygpath -m turns it into E:/...
abspath() {
    p=$(CDPATH= cd -- "$1" && pwd)
    if command -v cygpath >/dev/null 2>&1; then p=$(cygpath -m "$p"); fi
    printf '%s' "$p"
}

modroot=$(abspath "$(dirname -- "$0")")
if [ -z "$server" ]; then server="$modroot/../.."; fi
[ -f "$server/go.mod" ] || { echo "Server repo not found at $server (no go.mod)" >&2; exit 1; }
server=$(abspath "$server")
builddir="$modroot/build"
mkdir -p "$builddir"

# -- 1. Enable file: blank-imports the module package ------------------------
enabled="$builddir/modules_enabled.go"
cat > "$enabled" <<'GO'
// Code generated by GM-RoleBot-mod/mod-rebuild.sh. DO NOT EDIT.
// This file exists only inside the -overlay build; the on-disk
// modules/modules.go in the server repo is untouched.
package modules

import _ "gurimoon/modules/rolebots"
GO

# -- 2. Overlay map ----------------------------------------------------------
# Entries accumulate in $entries as JSON lines; paths have no quotes or
# backslashes to escape (abspath gives forward slashes).
entries=""
count=0
map() {
    entries="$entries${entries:+,
}    \"$1\": \"$2\""
    count=$((count + 1))
}
# bridge <server-relative target> <module-relative source>: a seam bridge
# file ADDED to a core package. Same list as mod-rebuild.ps1.
bridge() {
    [ -f "$modroot/$2" ] || { echo "missing module source: $modroot/$2" >&2; exit 1; }
    map "$server/$1" "$modroot/$2"
}

map "$server/modules/modules.go" "$enabled"

# esp: synthetic session, and the in-game browser kit (panel bands, icons,
# bars, YC dates) exported to the module's Corporate Portal sections.
bridge esp/sessionbot_mod.go                core/esp/sessionbot_mod.go
bridge esp/igbkit_mod.go                    core/esp/igbkit_mod.go
# PvP and chat seams.
bridge modapi/pvpbridge_mod.go              core/modapi/pvpbridge_mod.go
bridge cmd/gurimoon/rolebotpvp_mod.go     core/main/rolebotpvp_mod.go
bridge server/lsc/botspeak_mod.go           core/lsc/botspeak_mod.go
# Gang seam (connection-less pilot in a player gang).
bridge modapi/gangbridge_mod.go             core/modapi/gangbridge_mod.go
bridge cmd/gurimoon/rolebotgang_mod.go    core/main/rolebotgang_mod.go
# System-loading seam: publishes ensureSystemLoaded and the teardown through
# modapi.SpaceHooks.
bridge modapi/preloadbridge_mod.go          core/modapi/preloadbridge_mod.go
bridge cmd/gurimoon/rolebotpreload_mod.go core/main/rolebotpreload_mod.go
# Corporation push seam (bot CEOs): modapi.CorpHooks closures from main.
bridge modapi/corpbridge_mod.go             core/modapi/corpbridge_mod.go
bridge cmd/gurimoon/rolebotcorp_mod.go    core/main/rolebotcorp_mod.go
# Drone seam (bot drones in space): modapi.DroneHooks closures from main.
bridge modapi/dronebridge_mod.go            core/modapi/dronebridge_mod.go
bridge cmd/gurimoon/rolebotdrone_mod.go   core/main/rolebotdrone_mod.go
# Open-site seam (bots run the dungeons the core seeds): modapi.SiteHooks.
bridge modapi/sitebridge_mod.go             core/modapi/sitebridge_mod.go
bridge cmd/gurimoon/rolebotsite_mod.go    core/main/rolebotsite_mod.go
# Agent-mission seam (bots take and turn in missions): modapi.MissionHooks.
bridge modapi/missionbridge_mod.go          core/modapi/missionbridge_mod.go
bridge cmd/gurimoon/rolebotmission_mod.go core/main/rolebotmission_mod.go
# Corp allegiance: SetCorpFaction on npc.StandingsMap.
bridge npc/corpfaction_mod.go               core/npc/corpfaction_mod.go

# The module package itself: every .go under rolebots/, recursively, lands
# under <server>/modules/rolebots/ (a path with nothing on disk behind it).
srcroot="$modroot/rolebots"
[ -d "$srcroot" ] || { echo "No rolebots/ source tree in $modroot" >&2; exit 1; }
# Sorted so the map is stable between runs; the while loop reads the list
# from a temp file because a pipe would run it in a subshell.
list="$builddir/.rolebots-files"
find "$srcroot" -type f -name '*.go' | sort > "$list"
while IFS= read -r f; do
    rel=${f#"$srcroot"/}
    map "$server/modules/rolebots/$rel" "$f"
done < "$list"
rm -f "$list"

overlay="$builddir/overlay.json"
printf '{\n  "Replace": {\n%s\n  }\n}\n' "$entries" > "$overlay"
echo "overlay: $count file(s) mapped -> $overlay"

[ "$mode" = "overlay" ] && exit 0

# -- 3. Build ----------------------------------------------------------------
cd "$server"
case "$mode" in
    check)
        out="$builddir/gurimoon-check"
        case "$(go env GOOS)" in windows) out="$out.exe" ;; esac
        echo "=== compile check (server repo untouched) ==="
        go build -overlay "$overlay" -o "$out" ./cmd/gurimoon/
        echo "=== Build OK: $out ==="
        ;;
    build)
        echo "=== building server WITH rolebots module ==="
        go build -overlay "$overlay" ./cmd/gurimoon/
        echo "=== Build OK ==="
        ;;
esac
